/**
 * Сидит все округа и территории через Prisma (idempotent — upsert).
 *
 * Правила:
 * - Данные статические, соответствуют districts.sql
 * - Использует upsert по полю name (unique), безопасно запускать повторно
 * - Area: уникальность по [name, districtId]
 *
 * Возвращает список созданных/обновлённых округов.
 */
export async function seedDistricts(prisma: PrismaClient) {
    const districts: District[] = [];

    for (const data of DISTRICT_DATA) {
        const district = await prisma.district.upsert({
            where: { name: data.name },
            update: {},
            create: {
                name: data.name,
                mapId: data.mapId,
            },
        });

        for (const areaName of data.areas) {
            await prisma.area.upsert({
                where: { name_districtId: { name: areaName, districtId: district.id } },
                update: {},
                create: {
                    name: areaName,
                    districtId: district.id,
                },
            });
        }

        districts.push(district);
    }

    return districts;
}
